import { expect, test } from "@playwright/test";
import { AgentExportFile } from "../../src/contracts/agent";
import { VersionExportFile } from "../../src/contracts/version";
import { RunReportFile } from "../../src/contracts/run";
import { inputWorkbenchWorkflowDefinition } from "../fixtures/input-workbench-workflow";

test("桌面输入定义换序、引用核对、保存与五种真实输入运行形成证据", async ({ page }, testInfo) => {
  test.setTimeout(480_000);
  await page.setViewportSize({ width: 1440, height: 900 });
  const name = "输入定义核对-" + Date.now();
  const definition = inputWorkbenchWorkflowDefinition(name);
  const pageErrors: string[] = [];
  page.on("pageerror", (error) => pageErrors.push(error.message));
  await page.goto("/agents/new");
  await expect(page.getByRole("heading", { name: "从文件导入助手", exact: true })).toBeVisible();
  await page.getByLabel("选择助手定义文件").setInputFiles({ name: "input-workflow.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(definition)) });
  await page.waitForURL(/\/agents\/[0-9a-f-]+$/);
  await expect(page.getByRole("heading", { level: 1, name, exact: true })).toBeVisible();
  const agentPath = new URL(page.url()).pathname;
  const initialResponse = await page.request.get("/api" + agentPath + "/export");
  expect(initialResponse.ok()).toBe(true);
  const initial = AgentExportFile.parse(await initialResponse.json());
  await page.locator("summary").filter({ hasText: "运行输入字段" }).click();
  const inputs = page.getByRole("region", { name: "运行输入定义工作台", exact: true });
  await expect(inputs.getByLabel("字段 7 名称", { exact: true })).toBeDisabled();
  await inputs.getByRole("button", { name: "设为本次运行输入字段 7", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "纳入本次运行输入？", exact: true })).toContainText("不建立团队共享、私有权限或默认值");
  await page.getByRole("dialog").getByRole("button", { name: "返回", exact: true }).click();
  await expect(page.getByRole("button", { name: "保存草稿", exact: true })).toBeDisabled();
  await inputs.getByLabel("字段 1 显示名称", { exact: true }).fill("核对材料");
  await inputs.getByLabel("字段 1 业务说明", { exact: true }).fill("核对标记与数量；这是随草稿保存的设计说明");
  await inputs.getByRole("button", { name: "上移输入字段 3", exact: true }).click();
  await inputs.getByRole("button", { name: "上移输入字段 2", exact: true }).click();
  await expect(inputs.getByLabel("字段 1 名称", { exact: true })).toHaveValue("confirmed");
  await page.getByRole("button", { name: "撤销上一步修改", exact: true }).click();
  await expect(inputs.getByLabel("字段 1 名称", { exact: true })).toHaveValue("payload");
  await page.getByRole("button", { name: "重做上一步修改", exact: true }).click();
  await expect(inputs.getByLabel("字段 1 名称", { exact: true })).toHaveValue("confirmed");
  await inputs.getByRole("button", { name: "删除输入字段 6", exact: true }).click();
  await page.getByRole("dialog", { name: "删除这项输入定义？", exact: true }).getByRole("button", { name: "删除输入定义", exact: true }).click();
  await expect(inputs.getByLabel("字段 6 名称", { exact: true })).toHaveValue("legacy_note");
  await inputs.getByLabel("查找输入定义", { exact: true }).fill("核对材料");
  await expect(inputs.getByRole("list", { name: "输入定义列表" }).locator(":scope > li")).toHaveCount(1);
  await inputs.getByRole("button", { name: "查看关联流程步骤", exact: true }).click();
  const inspector = page.getByRole("complementary", { name: "节点详情" });
  await expect(inspector.getByLabel("判断数据", { exact: true })).toHaveValue("input.payload.flag");
  await page.getByRole("button", { name: "关闭节点详情" }).last().click();
  for (const width of [1280, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    for (const control of [inputs.getByLabel("字段 2 显示名称", { exact: true }), inputs.getByLabel("字段 2 业务说明", { exact: true }), inputs.getByRole("button", { name: "上移输入字段 2", exact: true })]) {
      await control.scrollIntoViewIfNeeded();
      const bounds = await control.evaluate((element) => {
        const rect = element.getBoundingClientRect();
        const panel = element.closest('section[aria-label="运行输入定义工作台"]')!.getBoundingClientRect();
        const hit = document.elementFromPoint(rect.left + rect.width / 2, rect.top + rect.height / 2);
        return { left: rect.left, right: rect.right, panelLeft: panel.left, panelRight: panel.right, hit: hit === element || element.contains(hit) };
      });
      expect(bounds.left).toBeGreaterThanOrEqual(bounds.panelLeft - 1);
      expect(bounds.right).toBeLessThanOrEqual(bounds.panelRight + 1);
      expect(bounds.hit).toBe(true);
    }
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  }
  if (process.env.CAPTURE_UI_AUDIT === "1") await inputs.screenshot({ path: "qa/workflow-input-workbench-desktop.png" });
  await inputs.getByRole("button", { name: "删除输入字段 2", exact: true }).click();
  await expect(page.getByRole("dialog")).toContainText("1 个关联步骤");
  await expect(page.getByRole("dialog")).toContainText("发布仍可能推导出同名输入");
  await page.getByRole("dialog").press("Escape");
  await expect(inputs.getByRole("button", { name: "删除输入字段 2", exact: true })).toBeFocused();
  await inputs.getByRole("button", { name: "清除输入筛选", exact: true }).click();
  await page.getByRole("button", { name: "保存草稿", exact: true }).click();
  await expect(page.getByRole("button", { name: "保存草稿", exact: true })).toBeDisabled();
  const savedResponse = await page.request.get("/api" + agentPath + "/export");
  expect(savedResponse.ok()).toBe(true);
  const saved = AgentExportFile.parse(await savedResponse.json());
  const expected = [definition.workflow.variables[2], { ...definition.workflow.variables[0], label: "核对材料", description: "核对标记与数量；这是随草稿保存的设计说明" }, definition.workflow.variables[1], definition.workflow.variables[3], definition.workflow.variables[4], definition.workflow.variables[6]];
  expect(saved.workflow.variables).toEqual(expected);
  expect(saved.workflow.nodes).toEqual(initial.workflow.nodes);
  await page.reload();
  await page.locator("summary").filter({ hasText: "运行输入字段" }).click();
  await expect(inputs.getByLabel("字段 2 业务说明", { exact: true })).toHaveValue(expected[1].description!);
  await expect(inputs.getByLabel("字段 6 名称", { exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "发布新版本", exact: true }).click();
  await expect(page.locator("#versions").getByText("当前版本", { exact: true })).toBeVisible();
  const frozenHref = (await page.locator("#versions").getByRole("link", { name: "下载此版本", exact: true }).getAttribute("href"))!;
  const frozenVersionId = new URL(frozenHref, page.url()).pathname.split("/").at(-2)!;
  const frozenResponse = await page.request.get(frozenHref);
  expect(frozenResponse.ok()).toBe(true);
  const frozenRaw = await frozenResponse.json();
  const frozen = VersionExportFile.parse(frozenRaw);
  expect(frozen.manifest.workflowSnapshot.variables).toEqual(expected);
  expect(frozen.manifest.inputContract.fields.map((field) => field.name)).toEqual(["confirmed", "payload", "quantity", "items", "note"]);
  expect(frozen.manifest.inputContract.fields.map((field) => field.type)).toEqual(["boolean", "object", "number", "array", "string"]);
  expect(frozenRaw.manifest.inputContract.fields.some((field: Record<string, unknown>) => Object.hasOwn(field, "description"))).toBe(false);
  const launcher = page.locator("#run");
  await expect(launcher.getByLabel("核对材料（必填）", { exact: true })).toHaveAccessibleDescription(expected[1].description!);
  await inputs.getByLabel("字段 2 业务说明", { exact: true }).fill("尚未发布的新草稿说明");
  await page.getByRole("button", { name: "保存草稿", exact: true }).click();
  await expect(page.getByRole("button", { name: "保存草稿", exact: true })).toBeDisabled();
  const newerDraftResponse = await page.request.get("/api" + agentPath + "/export");
  expect(newerDraftResponse.ok()).toBe(true);
  const newerDraft = AgentExportFile.parse(await newerDraftResponse.json());
  expect(newerDraft.workflow.variables[1].description).toBe("尚未发布的新草稿说明");
  await expect(launcher.getByLabel("核对材料（必填）", { exact: true })).toHaveAccessibleDescription(expected[1].description!);
  expect(launcher.getByText("尚未发布的新草稿说明", { exact: true })).toHaveCount(0);
  const names = await launcher.locator("form label > span").allTextContents();
  expect(names).toEqual(["是否核对（必填）", "核对材料（必填）", "业务数量（必填）", "待核对清单（选填）", "补充说明（选填）"]);
  const input = { confirmed: false, payload: { flag: "待核对", count: 0 }, quantity: 0, items: ["第一项", "第二项"], note: "本次桌面输入核对，请按保存表单处理。" };
  await launcher.getByRole("combobox", { name: "是否核对（必填）", exact: true }).selectOption("false");
  await launcher.getByLabel("核对材料（必填）", { exact: true }).fill(JSON.stringify(input.payload));
  await launcher.getByLabel("业务数量（必填）", { exact: true }).fill("0");
  await launcher.getByLabel("待核对清单（选填）", { exact: true }).fill(JSON.stringify(input.items));
  await launcher.getByLabel("补充说明（选填）", { exact: true }).fill(input.note);
  if (process.env.CAPTURE_UI_AUDIT === "1") { await launcher.scrollIntoViewIfNeeded(); await launcher.screenshot({ path: "qa/workflow-input-form-desktop.png" }); }
  await page.getByRole("button", { name: "开始试运行", exact: true }).click();
  await page.waitForURL(/\/runs\/[0-9a-f-]+$/);
  const runPath = new URL(page.url()).pathname;
  let report: ReturnType<typeof RunReportFile.parse> | undefined;
  await expect.poll(async () => {
    const response = await page.request.get("/api" + runPath + "/export");
    expect(response.ok()).toBe(true);
    report = RunReportFile.parse(await response.json());
    return report.run.status;
  }, { timeout: 180_000, intervals: [1000, 2000, 4000] }).toBe("completed");
  expect(report!.run.agentId).toBe(agentPath.split("/").at(-1));
  expect(report!.run.version).toBe(frozen.version.number);
  expect(report!.run.input).toEqual(input);
  const decision = report!.steps.find((step) => step.nodeType === "condition")!;
  expect(decision.output).toEqual({ matched: "文字命中", next: "text" });
  await expect(page.getByText("运行已完成", { exact: true })).toBeVisible();
  let previewPosts = 0;
  const countPreviewPosts = (request: { method(): string }) => { if (request.method() === "POST") previewPosts += 1; };
  await page.goto("/web-tools?version=" + frozenVersionId);
  const preview = page.getByRole("region", { name: "网页填写预览", exact: true });
  await expect(preview).toBeVisible();
  await expect(preview.getByLabel("核对材料（必填）", { exact: true })).toHaveAccessibleDescription("对象，使用大括号包裹内容 " + expected[1].description!);
  await expect(preview.getByText("尚未发布的新草稿说明", { exact: true })).toHaveCount(0);
  page.on("request", countPreviewPosts);
  await preview.getByRole("combobox", { name: "是否核对（必填）", exact: true }).selectOption("false");
  await preview.getByLabel("核对材料（必填）", { exact: true }).fill(JSON.stringify(input.payload));
  await preview.getByLabel("业务数量（必填）", { exact: true }).fill("0");
  await preview.getByRole("button", { name: "检查填写格式", exact: true }).click();
  await expect(preview.getByRole("status")).toContainText("已核对 3 项填写格式；没有提交或运行任务");
  expect(previewPosts).toBe(0);
  page.off("request", countPreviewPosts);
  if (process.env.CAPTURE_UI_AUDIT === "1") await preview.screenshot({ path: "qa/workflow-input-web-preview-desktop.png" });
  await testInfo.attach("真实输入定义保存与五类型运行", { body: JSON.stringify({ definitions: saved.workflow.variables, fields: frozen.manifest.inputContract.fields, publishedDescription: expected[1].description, newerDraftDescription: newerDraft.workflow.variables[1].description, previewPosts, version: report!.run.version, input: report!.run.input, decision: decision.output }, null, 2), contentType: "application/json" });
  expect(pageErrors).toEqual([]);
});
