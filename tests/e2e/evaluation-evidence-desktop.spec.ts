import { expect, test } from "@playwright/test";
import { VersionExportFile } from "../../src/contracts/version";
import { RunReportFile } from "../../src/contracts/run";
import { savedRunResultView } from "../../src/features/runs/run-result-view";
import { redactSensitiveData } from "../../src/server/domain/security/redact-sensitive";

test.use({ permissions: ["clipboard-read", "clipboard-write"] });

test("桌面真实验收的问题筛选、历史输入证据与运行详情往返", async ({ page }) => {
  test.setTimeout(360_000);
  await page.setViewportSize({ width: 1440, height: 900 });
  const marker = Date.now();
  const agentName = `验收证据核对-${marker}`;
  const passedName = `完成检查-${marker}`;
  const failedName = `缺少文字检查-${marker}`;
  const historicalInput = "请生成客户回复方案，保留本次验收输入";
  const originalExpectation = `不会出现在结果里的固定验收文字-${marker}`;
  const editedExpectation = `后来修改的规则-${marker}`;
  const pageErrors: string[] = [];
  page.on("pageerror", (error) => pageErrors.push(error.message));
  await page.goto("/agents/new");
  await page.getByLabel("助手名称").fill(agentName);
  await page.getByLabel("想让助手完成什么（至少 10 个字）").fill("收到客户咨询后生成回复方案，最后输出客户回复邮件");
  await page.getByRole("button", { name: "创建助手" }).click();
  await page.waitForURL(/\/agents\/[0-9a-f-]+$/, { timeout: 60_000 });
  const agentPath = new URL(page.url()).pathname;
  const evaluation = page.locator("#evaluation");
  for (const [name, expected] of [[passedName, ""], [failedName, originalExpectation]]) {
    await evaluation.getByLabel("样例名称").fill(name);
    await evaluation.getByLabel("结果应包含").fill(expected);
    await evaluation.getByLabel("运行输入", { exact: true }).fill(JSON.stringify({ input: historicalInput }));
    await evaluation.getByRole("button", { name: "添加样例", exact: true }).click();
    await expect(evaluation.getByLabel(`验收样例：${name}`, { exact: true })).toBeVisible();
  }
  await page.getByRole("button", { name: "发布新版本" }).click();
  await expect(page.getByText("候选版本 1 等待自动验收")).toBeVisible();
  const exportHref = await page.locator("#versions").getByRole("link", { name: "下载此版本", exact: true }).getAttribute("href");
  const exported = await page.request.get(exportHref!);
  expect(exported.ok()).toBe(true);
  const saved = VersionExportFile.parse(await exported.json());
  expect(saved.version.status).toBe("candidate");
  expect(saved.manifest.inputContract.fields.some((field) => field.name === "input")).toBe(true);
  expect(Object.values(saved.manifest.workflowSnapshot.nodes).some((node) => ["tool", "human", "knowledge", "wait"].includes(node.type))).toBe(false);
  const evaluationWrites: string[] = [];
  const observe = (request: import("@playwright/test").Request) => {
    if (!["GET", "HEAD"].includes(request.method())) evaluationWrites.push(new URL(request.url()).pathname);
  };
  page.on("request", observe);
  await evaluation.getByRole("button", { name: "运行全部样例", exact: true }).click();
  await expect(evaluation.getByRole("group", { name: "本页验收批次" })).toContainText("通过 1 / 失败 1 / 共 2", { timeout: 180_000 });
  expect(evaluationWrites).toEqual([agentPath]);
  page.off("request", observe);
  await expect(evaluation.getByLabel(`验收样例：${failedName}`, { exact: true }).getByRole("button", { name: "编辑", exact: true })).toBeEnabled();
  await evaluation.getByLabel(`验收样例：${failedName}`, { exact: true }).getByRole("button", { name: "编辑", exact: true }).click();
  await evaluation.getByLabel("业务输入", { exact: true }).fill("后来改过的当前样例输入，不能覆盖历史证据");
  await evaluation.getByLabel("结果应包含").fill(editedExpectation);
  await evaluation.getByRole("button", { name: "保存修改", exact: true }).click();
  await expect(evaluation.getByLabel("样例名称")).toHaveValue("");
  const writes: string[] = [];
  page.on("request", (request) => { if (!["GET", "HEAD"].includes(request.method())) writes.push(new URL(request.url()).pathname); });
  await evaluation.getByLabel("样例名称").fill("尚未保存的样例草稿");
  await evaluation.getByRole("link", { name: "核对这一轮样例", exact: true }).click();
  const selected = page.getByRole("region", { name: "所选验收的样例判定" });
  await expect(selected).toContainText("已读 2 条，匹配 2 条");
  await expect(evaluation.getByLabel("样例名称")).toHaveValue("尚未保存的样例草稿");
  await selected.getByRole("group", { name: "样例判定筛选" }).getByRole("button", { name: "未通过", exact: true }).click();
  await expect(selected.getByRole("list", { name: "本页样例判定" }).getByRole("listitem")).toHaveCount(1);
  await expect(selected).toContainText(originalExpectation);
  await expect(selected).not.toContainText(editedExpectation);
  await selected.getByLabel("按样例名称查找").fill(failedName);
  await selected.getByRole("button", { name: "查找", exact: true }).click();
  await expect(page).toHaveURL(/evaluationQuery=/);
  await expect(evaluation.getByLabel("样例名称")).toHaveValue("尚未保存的样例草稿");
  await selected.getByRole("link", { name: "核对运行证据", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: `核对运行证据 · ${failedName}`, exact: true });
  await expect(dialog.getByText("任务执行完成，但样例检查未通过。", { exact: true })).toBeVisible();
  const scopedReturn = new URL(page.url()).pathname + new URL(page.url()).search + "#evaluation";
  const detailHref = await dialog.getByRole("link", { name: "打开运行详情", exact: true }).getAttribute("href");
  const actualRunPath = new URL(detailHref!, page.url()).pathname;
  const actualResponse = await page.request.get(`/api${actualRunPath}/export`);
  expect(actualResponse.ok()).toBe(true);
  const report = RunReportFile.parse(await actualResponse.json());
  expect(report.run.sourceType).toBe("evaluation");
  expect(report.run.status).toBe("completed");
  expect(report.run.input).toEqual({ input: historicalInput });
  expect(report.run.version).toBe(saved.version.number);
  expect(report.run.result).not.toBeNull();
  await expect(dialog.getByRole("region", { name: "本次运行保存的输入" })).toContainText(historicalInput);
  await expect(dialog.getByRole("region", { name: "本次运行保存的输入" })).not.toContainText("后来改过的当前样例输入");
  await dialog.getByText("查看本次报告（开发者数据）", { exact: true }).click();
  const displayedReport = RunReportFile.parse(JSON.parse((await dialog.locator("pre").textContent())!));
  expect(displayedReport.run).toEqual(redactSensitiveData(report.run));
  const expectedResult = savedRunResultView(report.run);
  const expectedCopy = expectedResult.copyText || (typeof expectedResult.redactedResult === "string" ? expectedResult.redactedResult : JSON.stringify(expectedResult.redactedResult, null, 2));
  await dialog.getByRole("button", { name: "复制本次结果", exact: true }).click();
  await expect(dialog.getByRole("status")).toHaveText("已复制");
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(expectedCopy);
  for (const width of [1280, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    const bounds = await dialog.boundingBox();
    expect(bounds).not.toBeNull();
    expect(bounds!.x).toBeGreaterThanOrEqual(0);
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width);
    expect(bounds!.y).toBeGreaterThanOrEqual(0);
    expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(900);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  }
  if (process.env.CAPTURE_UI_AUDIT === "1") await page.screenshot({ path: "qa/evaluation-evidence-desktop.png" });
  await page.keyboard.press("Escape");
  await expect(dialog).not.toBeVisible();
  await expect(page).not.toHaveURL(/evaluationCase=/);
  await expect(evaluation.getByLabel("样例名称")).toHaveValue("尚未保存的样例草稿");
  await expect(selected.getByRole("link", { name: "核对运行证据", exact: true })).toBeFocused();
  await selected.getByRole("link", { name: "核对运行证据", exact: true }).click();
  await expect(dialog.getByRole("link", { name: "打开运行详情", exact: true })).toBeVisible();
  await dialog.getByRole("link", { name: "打开运行详情", exact: true }).click();
  const nextEvaluation = page.getByRole("region", { name: "重新验收说明", exact: true });
  await expect(page.getByRole("button", { name: "按原输入再次运行", exact: true })).toHaveCount(0);
  await expect(nextEvaluation).toContainText("运行全部启用中的样例");
  await expect(nextEvaluation).toContainText("最新可验收版本");
  await expect(nextEvaluation).toContainText("自动启用为正式版本");
  await expect(nextEvaluation.getByRole("link", { name: "返回验收记录", exact: true })).toHaveAttribute("href", scopedReturn);
  await nextEvaluation.getByRole("link", { name: "返回验收记录", exact: true }).click();
  await expect(dialog.getByText("任务执行完成，但样例检查未通过。", { exact: true })).toBeVisible();
  expect(writes).toEqual([]);
  await dialog.getByRole("link", { name: "打开运行详情", exact: true }).click();
  await expect(page.getByRole("link", { name: "返回验收证据", exact: true })).toHaveAttribute("href", scopedReturn);
  await page.getByRole("link", { name: "返回验收证据", exact: true }).click();
  await expect(dialog.getByText("任务执行完成，但样例检查未通过。", { exact: true })).toBeVisible();
  let release!: () => void;
  const pendingRead = new Promise<void>((resolve) => { release = resolve; });
  await page.route(`**/api${actualRunPath}/export`, async (route) => { await pendingRead; await route.continue(); });
  try {
    await dialog.getByRole("button", { name: "重新读取运行报告", exact: true }).click();
    await expect(dialog.getByRole("status")).toContainText("正在读取实际运行报告");
    await expect(dialog.getByRole("region", { name: "本次运行保存的输入" })).toHaveCount(0);
  } finally { release(); }
  await expect(dialog.getByRole("region", { name: "本次运行保存的输入" })).toContainText(historicalInput);
  await page.unroute(`**/api${actualRunPath}/export`);
  await page.keyboard.press("Escape");
  await expect(dialog).not.toBeVisible();
  if (process.env.CAPTURE_UI_AUDIT === "1") await page.screenshot({ path: "qa/evaluation-history-desktop.png" });
  const currentScope = new URL(page.url());
  currentScope.searchParams.append("evaluationBatch", currentScope.searchParams.get("evaluationBatch")!);
  await page.goto(currentScope.toString());
  await expect(page.getByRole("alert").filter({ hasText: "验收定位或筛选条件无效" })).toBeVisible();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.getByRole("button", { name: "清除验收定位与筛选", exact: true }).click();
  await expect(page).not.toHaveURL(/evaluationBatch=/);
  expect(writes).toEqual([]);
  expect(pageErrors).toEqual([]);
});
