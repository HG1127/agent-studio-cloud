import { expect, test } from "@playwright/test";
import { AgentExportFile } from "../../src/contracts/agent";
import { qualityGateRulesDraft } from "../fixtures/quality-gate-rules";

test("桌面四项质量规则真实导入、明确应用、保存与刷新，不执行业务任务", async ({ page }, testInfo) => {
  test.setTimeout(180000);
  await page.setViewportSize({ width: 1440, height: 900 });
  const errors: string[] = []; page.on("pageerror", (error) => errors.push(error.message));
  const definition = AgentExportFile.parse({ format: "agent-studio-cloud", formatVersion: 1, exportedAt: new Date().toISOString(), agent: { name: "质量规则保存核对-" + Date.now(), description: "核对草稿配置，不执行业务任务", intentText: "核对交付前四项质量规则及保存边界" }, workflow: qualityGateRulesDraft() });
  await page.goto("/agents/new");
  await page.getByLabel("选择助手定义文件").setInputFiles({ name: "quality-rules.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(definition)) });
  await page.waitForURL(/\/agents\/[0-9a-f-]+$/);
  const agentPath = new URL(page.url()).pathname;
  const readSaved = async () => { const response = await page.request.get("/api" + agentPath + "/export"); expect(response.ok()).toBe(true); return AgentExportFile.parse(await response.json()); };
  const initial = await readSaved(), writes: string[] = [];
  page.on("request", (request) => { if (["POST", "PUT", "PATCH", "DELETE"].includes(request.method())) writes.push(new URL(request.url()).pathname); });
  const locate = page.getByRole("combobox", { name: "定位流程步骤", exact: true });
  const open = async () => {
    await locate.selectOption("review-private");
    const toggle = page.getByRole("button", { name: /编辑交付质量规则|收起质量规则编辑/ });
    if (await toggle.getAttribute("aria-expanded") !== "true") await toggle.click();
    return page.getByRole("region", { name: "交付前质量规则编辑", exact: true });
  };
  let editor = await open(); await editor.getByRole("button", { name: "编辑质量规则", exact: true }).click();
  await editor.getByLabel("必须形成结果：生成方案", { exact: true }).uncheck();
  await editor.getByLabel("最低有效结果数量", { exact: true }).fill("0");
  await editor.getByLabel("核对已执行工具的回执", { exact: true }).uncheck();
  await editor.getByLabel("核对已执行人工步骤的决定", { exact: true }).uncheck();
  await expect(page.getByLabel("未应用配置提醒", { exact: true })).toContainText("1 处");
  await expect(page.getByRole("button", { name: "保存草稿", exact: true })).toBeDisabled();
  await locate.selectOption("writer-private"); editor = await open();
  await expect(editor.getByLabel("最低有效结果数量", { exact: true })).toHaveValue("0");
  await expect(editor.getByLabel("必须形成结果：生成方案", { exact: true })).not.toBeChecked();
  expect(writes).toEqual([]); expect((await readSaved()).workflow).toEqual(initial.workflow);
  await editor.getByRole("button", { name: "应用质量规则到画布", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "返回", exact: true }).click();
  await expect(editor.getByLabel("最低有效结果数量", { exact: true })).toHaveValue("0");
  await editor.getByRole("button", { name: "应用质量规则到画布", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "确认应用质量规则", exact: true }).click();
  await expect(page.getByLabel("未应用配置提醒", { exact: true })).toHaveCount(0); expect(writes).toEqual([]);
  const review = page.getByRole("region", { name: "交付前检查规则核对", exact: true });
  await expect(review.getByText("0 项", { exact: true })).toBeVisible();
  await expect(review.getByText("未要求核对", { exact: true })).toHaveCount(2);
  await page.getByRole("button", { name: "撤销上一步修改", exact: true }).click();
  await expect(review.getByText("1 项", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "重做上一步修改", exact: true }).click();
  await expect(review.getByText("0 项", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "保存草稿", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: /^草稿已保存$/ })).toBeVisible();
  const saved = await readSaved();
  expect(saved.workflow).toEqual({ ...initial.workflow, nodes: { ...initial.workflow.nodes, "review-private": { ...initial.workflow.nodes["review-private"], quality: { ...initial.workflow.nodes["review-private"].quality, requiredOutputTitles: [], minOutputCount: 0, checkToolReceipts: false, checkHumanBoundary: false } } } });
  expect(writes).toEqual([agentPath]);
  await page.reload(); editor = await open(); await editor.getByRole("button", { name: "编辑质量规则", exact: true }).click();
  await expect(editor.getByLabel("最低有效结果数量", { exact: true })).toHaveValue("0");
  await expect(editor.getByLabel("核对已执行工具的回执", { exact: true })).not.toBeChecked();
  await expect(editor.getByLabel("核对已执行人工步骤的决定", { exact: true })).not.toBeChecked();
  await editor.getByRole("button", { name: "取消质量填写", exact: true }).click();
  for (const width of [1280, 1440]) { await page.setViewportSize({ width, height: 900 }); expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true); }
  expect(errors).toEqual([]);
  await testInfo.attach("质量规则真实草稿保存边界", { body: JSON.stringify({ agentPath, initial: initial.workflow, saved: saved.workflow, writes, errors, businessExecution: false, rawDraftProvenance: false }, null, 2), contentType: "application/json" });
});
