import { expect, test } from "@playwright/test";
import { AgentExportFile } from "../../src/contracts/agent";
import { nodeContractDesktopDefinition } from "../fixtures/node-contract-desktop-workflow";

test("桌面未应用字段填写跨步骤保留、离页取消及真实保存边界", async ({ page }, testInfo) => {
  test.setTimeout(180_000);
  await page.setViewportSize({ width: 1440, height: 900 });
  const definition = nodeContractDesktopDefinition("未应用字段核对-" + Date.now());
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/agents/new");
  await page.getByLabel("选择助手定义文件").setInputFiles({ name: "unapplied-contracts.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(definition)) });
  await page.waitForURL(/\/agents\/[0-9a-f-]+$/);
  const agentPath = new URL(page.url()).pathname;
  const initialResponse = await page.request.get("/api" + agentPath + "/export");
  expect(initialResponse.ok()).toBe(true);
  const initial = AgentExportFile.parse(await initialResponse.json());
  const writes: string[] = [];
  page.on("request", (request) => { if (["POST", "PUT", "PATCH", "DELETE"].includes(request.method())) writes.push(new URL(request.url()).pathname); });
  const locator = page.getByRole("combobox", { name: "定位流程步骤", exact: true });
  const summary = page.getByLabel("当前步骤输入与结果约定", { exact: true });
  const panel = page.getByRole("region", { name: "当前步骤字段约定", exact: true });
  await locator.selectOption("deliver"); await summary.click();
  await panel.getByRole("button", { name: "开始配置输入映射", exact: true }).click();
  await panel.getByRole("button", { name: "添加字段映射", exact: true }).click();
  const row = panel.getByRole("group", { name: "字段映射 1", exact: true });
  await row.getByLabel("目标路径第 1 层", { exact: true }).fill("核对值");
  await row.getByLabel("字段来源", { exact: true }).selectOption("literal");
  await row.getByLabel("固定值（数据格式）", { exact: true }).fill("false");
  await panel.getByRole("button", { name: "编辑结果约定", exact: true }).click();
  await panel.getByLabel("结果字段规则", { exact: true }).fill("{");
  await panel.getByLabel("运行输入样例（数据格式）", { exact: true }).fill('{"样例":"只属于当前试算"}');
  await expect(page.getByLabel("未应用配置提醒")).toContainText("2 处");
  await expect(page.getByRole("button", { name: "保存草稿", exact: true })).toBeDisabled();
  await locator.selectOption("decision"); await locator.selectOption("deliver"); await summary.click();
  await expect(row.getByLabel("固定值（数据格式）", { exact: true })).toHaveValue("false");
  await expect(panel.getByLabel("结果字段规则", { exact: true })).toHaveValue("{");
  await expect(panel.getByLabel("运行输入样例（数据格式）", { exact: true })).toHaveValue("");
  await page.getByRole("button", { name: "关闭节点详情", exact: true }).last().click();
  await locator.selectOption("deliver"); await summary.click();
  await expect(panel.getByLabel("结果字段规则", { exact: true })).toHaveValue("{");
  let leavePrompt = "";
  page.once("dialog", async (dialog) => { leavePrompt = dialog.message(); await dialog.dismiss(); });
  const navigation = page.getByRole("navigation", { name: "主导航" });
  await navigation.getByRole("button", { name: "展开处理记录子入口", exact: true }).click();
  expect(leavePrompt).toBe("");
  await expect(page.getByLabel("未应用配置提醒")).toContainText("2 处");
  await navigation.getByRole("link", { name: "工具结果核对", exact: true }).click();
  expect(leavePrompt).toBe("页面还有未保存修改，确定离开当前页面吗？");
  await expect(page).toHaveURL(new RegExp(agentPath + "$"));
  await expect(page.getByLabel("未应用配置提醒")).toContainText("2 处");
  const unchangedResponse = await page.request.get("/api" + agentPath + "/export");
  expect(unchangedResponse.ok()).toBe(true);
  expect(AgentExportFile.parse(await unchangedResponse.json()).workflow).toEqual(initial.workflow);
  expect(writes).toEqual([]);
  for (const width of [1280, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    await expect(panel.getByLabel("结果字段规则", { exact: true })).toHaveValue("{");
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  }
  await panel.getByRole("button", { name: "取消编辑", exact: true }).click();
  await expect(page.getByLabel("未应用配置提醒")).toContainText("1 处");
  await panel.getByRole("button", { name: "校验并应用到画布草稿", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "返回", exact: true }).click();
  await expect(page.getByRole("button", { name: "保存草稿", exact: true })).toBeDisabled();
  await expect(row.getByLabel("固定值（数据格式）", { exact: true })).toHaveValue("false");
  await panel.getByRole("button", { name: "校验并应用到画布草稿", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "明确确认本次修改", exact: true }).click();
  await expect(page.getByLabel("未应用配置提醒")).toHaveCount(0);
  expect(writes).toEqual([]);
  await page.getByRole("button", { name: "保存草稿", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: /^草稿已保存$/ })).toBeVisible();
  await expect(page.getByRole("button", { name: "保存草稿", exact: true })).toBeDisabled();
  const savedResponse = await page.request.get("/api" + agentPath + "/export");
  expect(savedResponse.ok()).toBe(true);
  const saved = AgentExportFile.parse(await savedResponse.json());
  const mapping = { fields: [{ target: ["核对值"], source: { kind: "literal", value: false }, required: true }], includeUpstreamOutputs: false };
  expect(saved.workflow.nodes.deliver.inputMapping).toEqual(mapping);
  expect(saved.workflow.nodes.deliver.modelOutput).toEqual(initial.workflow.nodes.deliver.modelOutput);
  expect(saved.workflow).toEqual({ ...initial.workflow, nodes: { ...initial.workflow.nodes, deliver: { ...initial.workflow.nodes.deliver, inputMapping: mapping } } });
  expect(writes).toEqual([agentPath]);
  await page.reload(); await locator.selectOption("deliver"); await summary.click();
  await expect(row.getByLabel("固定值（数据格式）", { exact: true })).toHaveValue("false");
  await expect(panel.getByRole("button", { name: "编辑结果约定", exact: true })).toBeVisible();
  await expect(page.getByLabel("未应用配置提醒")).toHaveCount(0);
  expect(errors).toEqual([]);
  await testInfo.attach("真实未应用填写与保存边界", { body: JSON.stringify({ agentPath, leavePrompt, mapping, writes, before: initial.workflow, after: saved.workflow, errors }, null, 2), contentType: "application/json" });
});
