import { expect, test } from "@playwright/test";
import { AgentExportFile } from "../../src/contracts/agent";
import { HandoffContract } from "../../src/contracts/workflow";

test("桌面交接约定在顶层与步骤组保存后可重新读取，经验扩大须确认", async ({ page }) => {
  test.setTimeout(240_000);
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto("/agents/new");
  await page.getByLabel("助手名称").fill(`交接约定验收-${Date.now()}`);
  await page.getByLabel("想让助手完成什么（至少 10 个字）").fill("根据客户咨询整理回复草稿，输出可核对的回复内容");
  await page.getByRole("button", { name: "创建助手", exact: true }).click();
  await page.waitForURL(/\/agents\/[0-9a-f-]+$/);
  const agentUrl = page.url();
  const agentId = new URL(agentUrl).pathname.split("/").at(-1)!;
  await expect(page.getByRole("heading", { name: "流程设计" })).toBeVisible();
  const collaboration = page.getByRole("region", { name: "助手协作清单" });
  await expect(collaboration.getByText("当前草稿还没有助手协作步骤")).toBeVisible();
  await collaboration.getByRole("button", { name: "添加独立交接步骤" }).click();
  await expect(collaboration.getByText("包含未保存修改")).toBeVisible();
  const inspector = page.getByRole("complementary", { name: "节点详情" });
  const targetPicker = inspector.getByRole("combobox", { name: "接收助手", exact: true });
  const targetVersion = await targetPicker.locator('option:not([value=""])').first().getAttribute("value");
  expect(targetVersion, "交接验收需要真实已发布的接收助手").toBeTruthy();
  await targetPicker.selectOption(targetVersion!);
  const editor = inspector.getByRole("region", { name: "交接约定", exact: true });
  const deliverables = editor.getByLabel("必须交付", { exact: true });
  await deliverables.focus();
  await deliverables.press("Control+End");
  await deliverables.press("Enter");
  await deliverables.pressSequentially("核对引用来源");
  await expect(deliverables).toHaveValue(/\n核对引用来源$/);
  await editor.getByText(/传入字段约定 ·/).click();
  await editor.getByLabel("传入字段 1 名称", { exact: true }).fill("交接任务说明");
  await editor.getByText(/返回字段约定 ·/).click();
  await editor.getByLabel("返回字段 1 名称", { exact: true }).fill("接收结果");
  const scope = editor.getByLabel("经验传递范围", { exact: true });
  await expect(scope).toHaveValue("none");
  await scope.selectOption("team");
  const confirmation = page.getByRole("dialog", { name: "允许传递上游经验步骤结果？" });
  await expect(confirmation).toContainText("当前不会按共享名称单独筛选");
  await confirmation.getByRole("button", { name: "返回", exact: true }).click();
  await expect(scope).toHaveValue("none");
  await scope.selectOption("team");
  await confirmation.getByRole("button", { name: "确认允许传递" }).click();
  await expect(scope).toHaveValue("team");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  if (process.env.CAPTURE_UI_AUDIT === "1") {
    await editor.getByRole("heading", { name: "交接约定", exact: true }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: "qa/handoff-contract-desktop.png" });
  }
  await page.getByRole("button", { name: "关闭节点详情" }).last().click();

  await expect(collaboration.getByRole("heading", { name: "新增助手交接", exact: true })).toBeVisible();
  await collaboration.getByRole("button", { name: "编辑协作：主流程 · 新增助手交接" }).click();
  await expect(inspector.getByRole("combobox", { name: "接收助手", exact: true })).toHaveValue(targetVersion!);
  await page.getByRole("button", { name: "关闭节点详情" }).last().click();
  await page.getByRole("button", { name: "撤销上一步修改" }).click();
  await page.getByRole("button", { name: "重做上一步修改" }).click();
  await page.getByRole("button", { name: "保存草稿", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: /^草稿已保存$/ })).toBeVisible();

  await page.reload({ waitUntil: "domcontentloaded" });
  await expect(page.getByRole("heading", { name: "流程设计" })).toBeVisible();
  const position = page.getByRole("combobox", { name: "定位流程步骤" });
  const handoffId = await position.locator("option").filter({ hasText: "新增助手交接" }).getAttribute("value");
  await position.selectOption(handoffId!);
  await expect(inspector.getByRole("combobox", { name: "接收助手", exact: true })).toHaveValue(targetVersion!);
  const persistedEditor = inspector.getByRole("region", { name: "交接约定", exact: true });
  await persistedEditor.getByText(/传入字段约定 ·/).click();
  await expect(persistedEditor.getByLabel("传入字段 1 名称", { exact: true })).toHaveValue("交接任务说明");
  await expect(persistedEditor.getByLabel("经验传递范围", { exact: true })).toHaveValue("team");
  await page.getByRole("button", { name: "关闭节点详情" }).last().click();

  await page.getByRole("combobox", { name: "新增步骤类型" }).selectOption("subflow");
  await page.getByRole("combobox", { name: "新增步骤位置" }).selectOption("");
  await page.getByRole("button", { name: "添加", exact: true }).click();
  await inspector.getByRole("combobox", { name: "步骤组步骤 1 类型", exact: true }).selectOption("handoff");
  await inspector.getByRole("combobox", { name: "步骤组步骤 1 接收助手", exact: true }).selectOption(targetVersion!);
  const nested = inspector.getByRole("region", { name: "步骤组步骤 1 交接约定", exact: true });
  await nested.getByText(/返回字段约定 ·/).click();
  await nested.getByLabel("步骤组步骤 1 交接约定 返回字段 1 名称", { exact: true }).fill("步骤组交接结果");
  await expect(nested.getByLabel("步骤组步骤 1 交接约定 经验传递范围", { exact: true })).toHaveValue("none");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  if (process.env.CAPTURE_UI_AUDIT === "1") {
    await nested.getByRole("heading", { name: "交接约定", exact: true }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: "qa/handoff-contract-nested-desktop.png" });
  }
  await page.getByRole("button", { name: "关闭节点详情" }).last().click();
  await page.getByRole("button", { name: "保存草稿", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: /^草稿已保存$/ })).toBeVisible();
  const exported = await page.request.get(`/api/agents/${agentId}/export`);
  expect(exported.ok()).toBe(true);
  const saved = AgentExportFile.parse(await exported.json()).workflow;
  const handoff = Object.values(saved.nodes).find((node) => node.type === "handoff")!;
  const group = Object.values(saved.nodes).find((node) => node.type === "subflow")!;
  expect(handoff.toAgent?.versionId).toBe(targetVersion);
  expect(handoff.contract?.deliverables).toContain("核对引用来源");
  expect(handoff.contract?.inputSchema[0].label).toBe("交接任务说明");
  expect(handoff.contract?.outputSchema[0].label).toBe("接收结果");
  expect(handoff.contract?.memoryPolicy?.mode).toBe("team");
  expect(group.subflow?.steps[0]).toMatchObject({ type: "handoff", toAgent: { versionId: targetVersion } });
  const nestedContract = HandoffContract.parse(group.subflow?.steps[0].contract);
  expect(nestedContract.outputSchema[0].label).toBe("步骤组交接结果");
  expect(nestedContract.memoryPolicy?.mode).toBe("none");
  await expect(collaboration.getByText("当前已保存草稿")).toBeVisible();
  await expect(collaboration.getByText(/共 2 项协作步骤 · 呼叫 0 项 · 交接 2 项/)).toBeVisible();
  await collaboration.getByLabel("搜索协作步骤").fill("新增一组步骤");
  await expect(collaboration.getByText("显示第 1–1 项，共 1 项")).toBeVisible();
  const nestedRow = collaboration.getByRole("list", { name: "协作步骤" }).locator(":scope > li");
  await nestedRow.getByText("查看输入和返回约定", { exact: true }).click();
  await expect(nestedRow.getByText("步骤组交接结果", { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  if (process.env.CAPTURE_UI_AUDIT === "1") await page.screenshot({ path: "qa/collaboration-overview-desktop.png" });
  await nestedRow.getByRole("button", { name: /编辑协作：/ }).click();
  await expect(inspector.getByLabel("节点名称", { exact: true })).toHaveValue("新增一组步骤");
  await expect(inspector.getByRole("combobox", { name: "步骤组步骤 1 接收助手", exact: true })).toHaveValue(targetVersion!);
  await page.getByRole("button", { name: "关闭节点详情" }).last().click();
  await collaboration.getByRole("button", { name: "清除协作筛选" }).click();
  await expect(collaboration.getByText("显示第 1–2 项，共 2 项")).toBeVisible();
  await expect(page.getByRole("button", { name: "保存草稿", exact: true })).toBeDisabled();
});
