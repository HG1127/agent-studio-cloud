import { expect, test } from "@playwright/test";
import { AgentExportFile } from "../../src/contracts/agent";
import { aiReworkResetDraft } from "../fixtures/ai-rework-reset";

test("桌面返工默认恢复经真实导入、明确确认、撤销重做、保存与刷新，不执行任务", async ({ page }, testInfo) => {
  test.setTimeout(180000);
  await page.setViewportSize({ width: 1440, height: 900 });
  const errors: string[] = []; page.on("pageerror", (error) => errors.push(error.message));
  const definition = AgentExportFile.parse({ format: "agent-studio-cloud", formatVersion: 1, exportedAt: new Date().toISOString(), agent: { name: "返工默认保存核对-" + Date.now(), description: "只核对草稿设置，不执行业务任务", intentText: "核对次数与等待参数移除、实际保存及默认来源边界" }, workflow: aiReworkResetDraft() });
  await page.goto("/agents/new");
  await page.getByLabel("选择助手定义文件").setInputFiles({ name: "ai-rework-reset.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(definition)) });
  await page.waitForURL(/\/agents\/[0-9a-f-]+$/);
  const agentPath = new URL(page.url()).pathname;
  const readSaved = async () => { const response = await page.request.get("/api" + agentPath + "/export"); expect(response.ok()).toBe(true); return AgentExportFile.parse(await response.json()); };
  const initial = await readSaved(), writes: string[] = [];
  expect(initial.workflow.nodes["writer-private"].retry).toEqual({ maxAttempts: 1, backoffMs: 900 });
  page.on("request", (request) => { if (["POST", "PUT", "PATCH", "DELETE"].includes(request.method())) writes.push(new URL(request.url()).pathname); });
  const locate = page.getByRole("combobox", { name: "定位流程步骤", exact: true });
  const open = async () => {
    await locate.selectOption("writer-private");
    const toggle = page.getByLabel("当前步骤输入与结果约定", { exact: true });
    if (await toggle.evaluate((element) => (element.parentElement as HTMLDetailsElement).open) !== true) await toggle.click();
    return page.getByRole("region", { name: "智能处理自动返工上限", exact: true });
  };
  let editor = await open(); await editor.getByRole("button", { name: "编辑返工上限", exact: true }).click();
  await editor.getByLabel("包含首次处理的总尝试次数", { exact: true }).fill("8");
  await expect(page.getByLabel("未应用配置提醒", { exact: true })).toContainText("1 处");
  await expect(page.getByRole("button", { name: "保存草稿", exact: true })).toBeDisabled();
  await locate.selectOption("review-private"); editor = await open();
  await expect(editor.getByLabel("包含首次处理的总尝试次数", { exact: true })).toHaveValue("8");
  expect(writes).toEqual([]); expect((await readSaved()).workflow).toEqual(initial.workflow);
  await editor.getByRole("button", { name: "恢复质量返工默认设置", exact: true }).click();
  await expect(page.getByRole("dialog")).toContainText("最多额外返工一次");
  await expect(page.getByRole("dialog")).toContainText("这不等于禁止返工");
  await page.getByRole("dialog").getByRole("button", { name: "返回", exact: true }).click();
  await expect(editor.getByLabel("包含首次处理的总尝试次数", { exact: true })).toHaveValue("8");
  await editor.getByRole("button", { name: "恢复质量返工默认设置", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "确认恢复质量返工默认", exact: true }).click();
  await expect(page.getByLabel("未应用配置提醒", { exact: true })).toHaveCount(0);
  await expect(editor.getByText(/当前画布没有尝试设置/)).toBeVisible(); expect(writes).toEqual([]);
  await page.getByRole("button", { name: "撤销上一步修改", exact: true }).click();
  await expect(editor.getByText(/当前画布总尝试上限：1 次/)).toBeVisible();
  await page.getByRole("button", { name: "重做上一步修改", exact: true }).click();
  await expect(editor.getByText(/当前画布没有尝试设置/)).toBeVisible();
  await page.getByRole("button", { name: "保存草稿", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: /^草稿已保存$/ })).toBeVisible();
  const saved = await readSaved(), expectedNode = { ...initial.workflow.nodes["writer-private"] }; delete expectedNode.retry;
  expect(saved.workflow).toEqual({ ...initial.workflow, nodes: { ...initial.workflow.nodes, "writer-private": expectedNode } });
  expect(Object.hasOwn(saved.workflow.nodes["writer-private"], "retry")).toBe(false); expect(writes).toEqual([agentPath]);
  await page.reload(); editor = await open();
  await expect(editor.getByText(/当前画布没有尝试设置/)).toBeVisible();
  await editor.getByRole("button", { name: "设置返工上限", exact: true }).click();
  await expect(editor.getByRole("button", { name: "恢复质量返工默认设置", exact: true })).toHaveCount(0);
  await expect(editor.getByLabel("新设置所需的等待参数（毫秒）", { exact: true })).toHaveValue("");
  await editor.getByRole("button", { name: "取消本页填写", exact: true }).click();
  for (const width of [1280, 1440]) { await page.setViewportSize({ width, height: 900 }); expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true); }
  expect(errors).toEqual([]);
  await testInfo.attach("返工默认真实保存边界", { body: JSON.stringify({ agentPath, initial: initial.workflow, saved: saved.workflow, writes, errors, businessExecution: false, rawDraftProvenance: false }, null, 2), contentType: "application/json" });
});
