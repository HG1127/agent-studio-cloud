import { expect, test } from "@playwright/test";
import { AgentExportFile } from "../../src/contracts/agent";
import { qualityGateRulesDraft } from "../fixtures/quality-gate-rules";

test("桌面未应用返工填写阻止按钮和快捷键，取消后仅保存明确接收的质量规则", async ({ page }, testInfo) => {
  test.setTimeout(180000);
  await page.setViewportSize({ width: 1440, height: 900 });
  const errors: string[] = []; page.on("pageerror", (error) => errors.push(error.message));
  const definition = AgentExportFile.parse({ format: "agent-studio-cloud", formatVersion: 1, exportedAt: new Date().toISOString(),
    agent: { name: "保存填写保护核对-" + Date.now(), description: "只核对草稿保存边界", intentText: "核对未应用填写与已接收配置的保存边界" }, workflow: qualityGateRulesDraft() });
  await page.goto("/agents/new");
  await page.getByLabel("选择助手定义文件").setInputFiles({ name: "canvas-save-protection.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(definition)) });
  await page.waitForURL(/\/agents\/[0-9a-f-]+$/);
  const agentPath = new URL(page.url()).pathname;
  const readSaved = async () => { const response = await page.request.get("/api" + agentPath + "/export"); expect(response.ok()).toBe(true); return AgentExportFile.parse(await response.json()); };
  const initial = await readSaved(), writes: string[] = [];
  page.on("request", (request) => { if (["POST", "PUT", "PATCH", "DELETE"].includes(request.method())) writes.push(new URL(request.url()).pathname); });
  const locate = page.getByRole("combobox", { name: "定位流程步骤", exact: true });
  await locate.selectOption("review-private");
  await page.getByRole("button", { name: "编辑交付质量规则", exact: true }).click();
  const quality = page.getByRole("region", { name: "交付前质量规则编辑", exact: true });
  await quality.getByRole("button", { name: "编辑质量规则", exact: true }).click();
  await quality.getByLabel("最低有效结果数量", { exact: true }).fill("0");
  await quality.getByRole("button", { name: "应用质量规则到画布", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "确认应用质量规则", exact: true }).click();
  const save = page.getByRole("button", { name: "保存草稿", exact: true }); await expect(save).toBeEnabled();
  await locate.selectOption("writer-private");
  await page.getByLabel("当前步骤输入与结果约定", { exact: true }).click();
  let rework = page.getByRole("region", { name: "智能处理自动返工上限", exact: true });
  await rework.getByRole("button", { name: "编辑返工上限", exact: true }).click();
  await expect(save).toBeDisabled();
  await expect(page.getByLabel("未应用配置提醒", { exact: true })).toContainText("1 处");
  await expect(rework.getByLabel("包含首次处理的总尝试次数", { exact: true })).toHaveValue(String(initial.workflow.nodes["writer-private"].retry!.maxAttempts));
  await rework.getByLabel("包含首次处理的总尝试次数", { exact: true }).press("Meta+s");
  await expect(page.getByRole("alert").filter({ hasText: "仍有未应用填写" })).toBeVisible();
  expect(writes).toEqual([]); expect((await readSaved()).workflow).toEqual(initial.workflow);
  await rework.getByLabel("包含首次处理的总尝试次数", { exact: true }).fill("4");
  await expect(save).toBeDisabled();
  await rework.getByLabel("包含首次处理的总尝试次数", { exact: true }).press("Control+s");
  await expect(page.getByRole("alert").filter({ hasText: "仍有未应用填写" })).toBeVisible();
  expect(writes).toEqual([]); expect((await readSaved()).workflow).toEqual(initial.workflow);
  await locate.selectOption("review-private"); await locate.selectOption("writer-private");
  await page.getByLabel("当前步骤输入与结果约定", { exact: true }).click();
  rework = page.getByRole("region", { name: "智能处理自动返工上限", exact: true });
  await expect(rework.getByLabel("包含首次处理的总尝试次数", { exact: true })).toHaveValue("4");
  await expect(save).toBeDisabled();
  await rework.getByRole("button", { name: "取消本页填写", exact: true }).click();
  await expect(save).toBeEnabled();
  await save.click(); await expect(page.getByRole("status").filter({ hasText: /^草稿已保存$/ })).toBeVisible();
  const saved = await readSaved();
  expect(saved.workflow).toEqual({ ...initial.workflow, nodes: { ...initial.workflow.nodes, "review-private": { ...initial.workflow.nodes["review-private"], quality: { ...initial.workflow.nodes["review-private"].quality!, minOutputCount: 0 } } } });
  expect(saved.workflow.nodes["writer-private"].retry).toEqual(initial.workflow.nodes["writer-private"].retry);
  expect(writes).toEqual([agentPath]);
  await page.reload(); await locate.selectOption("writer-private");
  await page.getByLabel("当前步骤输入与结果约定", { exact: true }).click();
  rework = page.getByRole("region", { name: "智能处理自动返工上限", exact: true });
  await rework.getByRole("button", { name: "编辑返工上限", exact: true }).click();
  await expect(rework.getByLabel("包含首次处理的总尝试次数", { exact: true })).toHaveValue(String(initial.workflow.nodes["writer-private"].retry!.maxAttempts));
  await rework.getByRole("button", { name: "取消本页填写", exact: true }).click();
  for (const width of [1280, 1440]) { await page.setViewportSize({ width, height: 900 }); expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true); }
  expect(errors).toEqual([]);
  await testInfo.attach("真实保存未应用填写边界", { body: JSON.stringify({ agentPath, initial: initial.workflow, saved: saved.workflow, writes, errors, businessExecution: false, rawDraftProvenance: false }, null, 2), contentType: "application/json" });
});
