import { expect, test } from "@playwright/test";
import { AgentExportFile } from "../../src/contracts/agent";
import { VersionExportFile } from "../../src/contracts/version";
import { RunReportFile } from "../../src/contracts/run";
import { InputMappingPreviewResult } from "../../src/contracts/input-mapping-preview";
import { nodeContractDesktopDefinition } from "../fixtures/node-contract-desktop-workflow";
import { contractSchema } from "../fixtures/node-contract-workflow";

test("桌面步骤字段约定实际保存、冻结并进入模拟模式真实运行回执", async ({ page }, testInfo) => {
  test.setTimeout(480_000);
  await page.setViewportSize({ width: 1440, height: 900 });
  const name = "步骤字段约定核对-" + Date.now();
  const definition = nodeContractDesktopDefinition(name);
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/agents/new");
  await page.getByLabel("选择助手定义文件").setInputFiles({
    name: "node-contracts.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(definition)),
  });
  await page.waitForURL(/\/agents\/[0-9a-f-]+$/);
  const agentPath = new URL(page.url()).pathname;
  await expect(page.getByRole("heading", { level: 1, name, exact: true })).toBeVisible();
  await page.getByRole("combobox", { name: "定位流程步骤", exact: true }).selectOption("deliver");
  await page.getByLabel("当前步骤输入与结果约定", { exact: true }).click();
  const panel = page.getByRole("region", { name: "当前步骤字段约定", exact: true });
  await panel.getByRole("button", { name: "开始配置输入映射", exact: true }).click();
  await panel.getByRole("button", { name: "添加字段映射", exact: true }).click();
  const row = panel.getByRole("group", { name: "字段映射 1", exact: true });
  await row.getByLabel("目标路径第 1 层", { exact: true }).fill("路径.核对");
  await row.getByLabel("字段来源", { exact: true }).selectOption("output");
  await row.getByLabel("来源步骤", { exact: true }).selectOption("decision");
  await row.getByRole("button", { name: "为来源路径添加一层", exact: true }).click();
  await row.getByLabel("来源路径第 1 层", { exact: true }).fill("matched");
  await panel.getByLabel("运行输入样例（数据格式）", { exact: true }).fill("{}");
  await panel.getByRole("button", { name: "添加成果样例", exact: true }).click();
  await panel.getByLabel("样例来源步骤", { exact: true }).selectOption("decision");
  await panel.getByLabel("成果样例内容（数据格式）", { exact: true }).fill('{"matched":"文字命中"}');
  const previewReply = page.waitForResponse((response) => new URL(response.url()).pathname === "/api/workflows/input-preview");
  await panel.getByRole("button", { name: "提交样例做只读试算", exact: true }).click();
  const preview = InputMappingPreviewResult.parse(await (await previewReply).json());
  expect(preview).toMatchObject({ ok: true, executed: false, scope: "field-mapping", input: { "路径.核对": "文字命中" }, outputs: {} });
  await expect(page.getByRole("button", { name: "保存草稿", exact: true })).toBeDisabled();
  await panel.getByRole("button", { name: "校验并应用到画布草稿", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "返回", exact: true }).click();
  await expect(page.getByRole("button", { name: "保存草稿", exact: true })).toBeDisabled();
  await panel.getByRole("button", { name: "校验并应用到画布草稿", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "明确确认本次修改", exact: true }).click();
  await page.getByRole("button", { name: "撤销上一步修改", exact: true }).click();
  await expect(page.getByRole("button", { name: "保存草稿", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "重做上一步修改", exact: true }).click();
  await panel.getByRole("button", { name: "编辑结果约定", exact: true }).click();
  await panel.getByLabel("额外格式修正次数", { exact: true }).selectOption("0");
  await panel.getByLabel("结果请求方式", { exact: true }).selectOption("json-schema");
  await panel.getByLabel("结果字段规则", { exact: true }).fill(JSON.stringify(contractSchema));
  await panel.getByRole("button", { name: "应用到当前草稿", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "确认替换约定", exact: true }).click();
  await page.getByRole("button", { name: "保存草稿", exact: true }).click();
  await expect(page.getByRole("button", { name: "保存草稿", exact: true })).toBeDisabled();
  const exportResponse = await page.request.get("/api" + agentPath + "/export");
  expect(exportResponse.ok()).toBe(true);
  const saved = AgentExportFile.parse(await exportResponse.json());
  const mapping = { fields: [{ target: ["路径.核对"], source: { kind: "output", nodeId: "decision", path: ["matched"] }, required: true }], includeUpstreamOutputs: false };
  const modelOutput = { ...definition.workflow.nodes.deliver.modelOutput!, providerMode: "json-schema" as const, maxRepairAttempts: 0 };
  expect(saved.workflow.nodes.deliver.inputMapping).toEqual(mapping);
  expect(saved.workflow.nodes.deliver.modelOutput).toEqual(modelOutput);
  expect(saved.workflow.nodes.deliver.next).toBe(definition.workflow.nodes.deliver.next);
  await page.reload();
  await page.getByRole("combobox", { name: "定位流程步骤", exact: true }).selectOption("deliver");
  await page.getByLabel("当前步骤输入与结果约定", { exact: true }).click();
  await expect(panel.getByLabel("目标路径第 1 层", { exact: true })).toHaveValue("路径.核对");
  await expect(panel.getByLabel("来源路径第 1 层", { exact: true })).toHaveValue("matched");
  await page.getByRole("button", { name: "发布新版本", exact: true }).click();
  await expect(page.locator("#versions").getByText("当前版本", { exact: true })).toBeVisible();
  const frozenHref = (await page.locator("#versions").getByRole("link", { name: "下载此版本", exact: true }).getAttribute("href"))!;
  const frozenResponse = await page.request.get(frozenHref);
  expect(frozenResponse.ok()).toBe(true);
  const frozen = VersionExportFile.parse(await frozenResponse.json());
  expect(frozen.manifest.workflowSnapshot.nodes.deliver.inputMapping).toEqual(mapping);
  expect(frozen.manifest.workflowSnapshot.nodes.deliver.modelOutput).toEqual(modelOutput);
  // 固定样例只属于明确的模拟验收模式，不发真实提供商请求或冒充真实模型输出。
  expect(frozen.manifest.resourceSelection?.model.mock).toBe(true);
  const launcher = page.locator("#run");
  const inputField = frozen.manifest.inputContract.fields[0];
  await launcher.getByLabel((inputField.label?.trim() || "业务信息 1") + "（必填）", { exact: true }).fill('{"flag":"待核对","count":0}');
  await launcher.getByRole("button", { name: "开始试运行", exact: true }).click();
  await page.waitForURL(/\/runs\/[0-9a-f-]+$/);
  const runPath = new URL(page.url()).pathname;
  let report: ReturnType<typeof RunReportFile.parse> | undefined;
  await expect.poll(async () => {
    const response = await page.request.get("/api" + runPath + "/export");
    expect(response.ok()).toBe(true);
    report = RunReportFile.parse(await response.json());
    return report.run.status;
  }, { timeout: 180_000, intervals: [1000, 2000, 4000] }).toBe("completed");
  expect(report!.run.result).toEqual({ 交付: { 金额: 0, 同意: false } });
  expect(report!.steps.find((step) => step.nodeId === "deliver")!.output).toMatchObject({ output: { 金额: 0, 同意: false }, mock: true, repairCount: 0 });
  await expect(page.getByText("运行已完成", { exact: true })).toBeVisible();
  await expect(page.locator("#result pre")).toContainText('"金额": 0');
  await expect(page.locator("#result pre")).toContainText('"同意": false');
  expect(errors).toEqual([]);
  await testInfo.attach("步骤字段保存冻结与真实模拟回执", { body: JSON.stringify({
    agentPath, runPath, mapping, modelOutput, frozenVersion: frozen.version.number,
    input: report!.run.input, result: report!.run.result, declaredMockMode: true, errors,
  }, null, 2), contentType: "application/json" });
});
