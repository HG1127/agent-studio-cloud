import { expect, test } from "@playwright/test";
import { AgentExportFile } from "../../src/contracts/agent";
import { qualityGateReworkDraft } from "../fixtures/quality-gate-rework";

test("桌面质量核对与有限返工真实保存、刷新、撤销，不执行任务", async ({ page }, testInfo) => {
  test.setTimeout(180000);
  await page.setViewportSize({ width: 1440, height: 900 });
  const errors: string[] = []; page.on("pageerror", (error) => errors.push(error.message));
  const name = "质量与返工核对-" + Date.now(), definition = AgentExportFile.parse({ format: "agent-studio-cloud", formatVersion: 1, exportedAt: new Date().toISOString(), agent: { name, description: "核对流程设置，不执行业务操作", intentText: "核对当前质量规则来源、智能处理尝试上限及真实草稿保存边界" }, workflow: qualityGateReworkDraft() });
  await page.goto("/agents/new");
  await page.getByLabel("选择助手定义文件").setInputFiles({ name: "quality-rework.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(definition)) });
  await page.waitForURL(/\/agents\/[0-9a-f-]+$/);
  const agentPath = new URL(page.url()).pathname;
  const readSaved = async () => { const response = await page.request.get("/api" + agentPath + "/export"); expect(response.ok()).toBe(true); return AgentExportFile.parse(await response.json()); };
  const initial = await readSaved(), writes: string[] = [];
  page.on("request", (request) => { if (["POST", "PUT", "PATCH", "DELETE"].includes(request.method())) writes.push(new URL(request.url()).pathname); });
  const locate = page.getByRole("combobox", { name: "定位流程步骤", exact: true });
  await locate.selectOption("review-private");
  const quality = page.getByRole("region", { name: "交付前检查规则核对", exact: true });
  await expect(quality.getByText(/以下只说明当前有效设置/)).toBeVisible();
  await expect(quality.getByText("原始字段已保存", { exact: true })).toHaveCount(0);
  await quality.getByRole("button", { name: "定位来源步骤：生成方案", exact: true }).click();
  await expect(page.getByLabel("节点名称", { exact: true })).toHaveValue("生成方案");
  const open = async () => { await locate.selectOption("writer-private"); await page.getByLabel("当前步骤输入与结果约定", { exact: true }).click(); return page.getByRole("region", { name: "智能处理自动返工上限", exact: true }); };
  let editor = await open();
  await editor.getByRole("button", { name: "编辑返工上限", exact: true }).click();
  await editor.getByLabel("包含首次处理的总尝试次数", { exact: true }).fill("3");
  await expect(page.getByLabel("未应用配置提醒", { exact: true })).toContainText("1 处");
  await expect(page.getByRole("button", { name: "保存草稿", exact: true })).toBeDisabled();
  await locate.selectOption("review-private"); editor = await open();
  await expect(editor.getByLabel("包含首次处理的总尝试次数", { exact: true })).toHaveValue("3");
  expect(writes).toEqual([]); expect((await readSaved()).workflow).toEqual(initial.workflow);
  await editor.getByRole("button", { name: "应用到画布草稿", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "返回", exact: true }).click();
  await expect(editor.getByLabel("包含首次处理的总尝试次数", { exact: true })).toHaveValue("3");
  await editor.getByRole("button", { name: "应用到画布草稿", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "确认应用返工上限", exact: true }).click();
  await expect(page.getByLabel("未应用配置提醒", { exact: true })).toHaveCount(0); expect(writes).toEqual([]);
  await page.getByRole("button", { name: "撤销上一步修改", exact: true }).click();
  await expect(editor.getByText(/当前画布总尝试上限：2 次/)).toBeVisible();
  await page.getByRole("button", { name: "重做上一步修改", exact: true }).click();
  await expect(editor.getByText(/当前画布总尝试上限：3 次/)).toBeVisible();
  await page.getByRole("button", { name: "保存草稿", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: /^草稿已保存$/ })).toBeVisible();
  const saved = await readSaved(), expected = { ...initial.workflow, nodes: { ...initial.workflow.nodes, "writer-private": { ...initial.workflow.nodes["writer-private"], retry: { ...initial.workflow.nodes["writer-private"].retry!, maxAttempts: 3 } } } };
  expect(saved.workflow).toEqual(expected); expect(writes).toEqual([agentPath]);
  await page.reload(); editor = await open(); await expect(editor.getByText(/当前画布总尝试上限：3 次/)).toBeVisible();
  for (const width of [1280, 1440]) { await page.setViewportSize({ width, height: 900 }); expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true); }
  expect(errors).toEqual([]);
  await testInfo.attach("质量与返工真实保存边界", { body: JSON.stringify({ agentPath, initial: initial.workflow, saved: saved.workflow, writes, errors, executedRun: false, originalDraftFieldsProven: false }, null, 2), contentType: "application/json" });
});
