import { expect, test } from "@playwright/test";
import { AgentExportFile } from "../../src/contracts/agent";
import { VersionExportFile } from "../../src/contracts/version";
import { RunReportFile } from "../../src/contracts/run";
import { conditionWorkflowDefinition } from "../fixtures/condition-workflow";

test("桌面设计检查筛选、定位、确认修复与已发布版本隔离形成真实证据", async ({ page }, testInfo) => {
  test.setTimeout(480_000);
  await page.setViewportSize({ width: 1440, height: 900 });
  const name = "设计修复核对-" + Date.now();
  const definition = conditionWorkflowDefinition(name);
  const original = Object.values(definition.workflow.nodes).find((node) => node.type === "condition")!;
  const pageErrors: string[] = [];
  page.on("pageerror", (error) => pageErrors.push(error.message));
  await page.goto("/agents/new");
  await expect(page.getByRole("heading", { name: "从文件导入助手", exact: true })).toBeVisible();
  await page.getByLabel("选择助手定义文件").setInputFiles({ name: "audit-workflow.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(definition)) });
  await page.waitForURL(/\/agents\/[0-9a-f-]+$/);
  await expect(page.getByRole("heading", { level: 1, name, exact: true })).toBeVisible();
  const agentPath = new URL(page.url()).pathname;
  await page.getByRole("button", { name: "发布新版本", exact: true }).click();
  await expect(page.locator("#versions").getByText("当前版本", { exact: true })).toBeVisible();
  const frozenHref = (await page.locator("#versions").getByRole("link", { name: "下载此版本", exact: true }).getAttribute("href"))!;
  const frozenResponse = await page.request.get(frozenHref);
  expect(frozenResponse.ok()).toBe(true);
  const frozen = VersionExportFile.parse(await frozenResponse.json());
  expect(frozen.manifest.workflowSnapshot.nodes[original.id].condition).toEqual(original.condition);

  const inspector = page.getByRole("complementary", { name: "节点详情" });
  const audit = page.getByRole("region", { name: "设计检查", exact: true });
  await page.getByRole("combobox", { name: "定位流程步骤" }).selectOption(original.id);
  await inspector.getByLabel("其余情况的目标步骤").selectOption("");
  await page.getByRole("button", { name: "关闭节点详情" }).last().click();
  await expect(page.getByRole("button", { name: "保存草稿", exact: true })).toBeEnabled();
  await audit.getByRole("button", { name: "重新读取设计检查", exact: true }).click();
  await expect(page.getByRole("button", { name: "保存草稿", exact: true })).toBeEnabled();
  await expect(audit).toContainText("本页未保存的修改尚未重新检查");
  await page.getByRole("button", { name: "保存草稿", exact: true }).click();
  await expect(page.getByRole("button", { name: "保存草稿", exact: true })).toBeDisabled();
  await expect(audit.getByText("条件缺少兜底路径", { exact: true })).toBeVisible();
  const beforeResponse = await page.request.get("/api" + agentPath + "/export");
  expect(beforeResponse.ok()).toBe(true);
  const before = AgentExportFile.parse(await beforeResponse.json());
  expect(before.workflow.nodes[original.id].condition!.defaultNext).toBeNull();

  await audit.getByLabel("问题级别").selectOption("warning");
  await audit.getByLabel("处理方式").selectOption("automatic");
  await audit.getByLabel("查找设计问题").fill("兜底路径");
  const issue = audit.getByRole("list", { name: "设计问题列表" }).getByRole("listitem");
  await expect(issue).toHaveCount(1);
  await issue.getByRole("button", { name: "在流程中查看", exact: true }).click();
  await expect(inspector.getByLabel("其余情况的目标步骤")).toHaveValue("");
  await page.getByRole("button", { name: "关闭节点详情" }).last().click();
  for (const width of [1280, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    for (const control of [audit.getByLabel("查找设计问题"), audit.getByLabel("问题级别"), audit.getByLabel("处理方式"), audit.getByRole("button", { name: "应用安全修复", exact: true })]) {
      await control.scrollIntoViewIfNeeded();
      const bounds = await control.evaluate((element) => {
        const rect = element.getBoundingClientRect();
        const panel = element.closest("#audit")!.getBoundingClientRect();
        const hit = document.elementFromPoint(rect.left + rect.width / 2, rect.top + rect.height / 2);
        return { left: rect.left, right: rect.right, panelLeft: panel.left, panelRight: panel.right, hit: hit === element || element.contains(hit) };
      });
      expect(bounds.left).toBeGreaterThanOrEqual(bounds.panelLeft - 1);
      expect(bounds.right).toBeLessThanOrEqual(bounds.panelRight + 1);
      expect(bounds.hit).toBe(true);
    }
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  }
  await audit.getByLabel("查找设计问题").fill("不会命中任何问题");
  await expect(audit).toContainText("没有符合筛选的设计问题");
  await expect(audit.getByText("当前设计检查通过。", { exact: true })).toHaveCount(0);
  const writes: string[] = [];
  const observe = (request: import("@playwright/test").Request) => { if (!["GET", "HEAD"].includes(request.method())) writes.push(new URL(request.url()).pathname); };
  page.on("request", observe);
  const trigger = audit.getByRole("button", { name: "应用安全修复", exact: true });
  await trigger.click();
  const dialog = page.getByRole("dialog", { name: "确认应用安全修复", exact: true });
  await expect(dialog).toContainText("全部可自动修复问题，不限于当前筛选结果");
  await dialog.getByRole("button", { name: "返回", exact: true }).click();
  expect(writes).toEqual([]);
  await expect(trigger).toBeFocused();
  await trigger.press("Enter");
  await expect(dialog).toBeVisible();
  await dialog.press("Escape");
  await expect(dialog).toHaveCount(0);
  expect(writes).toEqual([]);
  await trigger.click();
  if (process.env.CAPTURE_UI_AUDIT === "1") await page.screenshot({ path: "qa/design-audit-confirm-desktop.png" });
  await dialog.getByRole("button", { name: "确认修复已保存流程", exact: true }).click();
  const result = audit.getByRole("region", { name: "本次修复返回结果", exact: true });
  await expect(result).toContainText(`为「${original.title}」补充其他情况路径`);
  await expect(result).toContainText("后端报告剩余 0 个阻塞问题");
  await expect(dialog).toHaveCount(0);
  expect(writes).toEqual([agentPath]);
  page.off("request", observe);
  await audit.getByRole("button", { name: "清除筛选", exact: true }).click();
  await expect(audit.getByText("条件缺少兜底路径", { exact: true })).toHaveCount(0);
  const resultText = await result.innerText();
  if (process.env.CAPTURE_UI_AUDIT === "1") { await audit.scrollIntoViewIfNeeded(); await audit.screenshot({ path: "qa/design-audit-result-desktop.png" }); }
  const afterResponse = await page.request.get("/api" + agentPath + "/export");
  expect(afterResponse.ok()).toBe(true);
  const after = AgentExportFile.parse(await afterResponse.json());
  const updated = after.workflow.nodes[original.id].condition!;
  expect(updated.defaultNext).not.toBeNull();
  expect(after.workflow.nodes[updated.defaultNext!]).toBeDefined();
  expect(updated.branches).toEqual(original.condition!.branches);
  const unchangedResponse = await page.request.get(frozenHref);
  expect(unchangedResponse.ok()).toBe(true);
  const unchangedVersion = VersionExportFile.parse(await unchangedResponse.json());
  expect(unchangedVersion.manifest).toEqual(frozen.manifest);
  await page.reload();
  await page.getByRole("combobox", { name: "定位流程步骤" }).selectOption(original.id);
  await expect(inspector.getByLabel("其余情况的目标步骤")).toHaveValue(updated.defaultNext!);
  await page.getByRole("button", { name: "关闭节点详情" }).last().click();
  await page.goto(agentPath + "#run");
  const payloadField = frozen.manifest.inputContract.fields.find((field) => field.name === "payload")!;
  const payload = { flag: "待核对", count: 0 };
  await page.locator("#run").getByLabel(payloadField.label?.trim() || "业务信息 1").fill(JSON.stringify(payload));
  await page.getByRole("button", { name: "开始试运行", exact: true }).click();
  await page.waitForURL(/\/runs\/[0-9a-f-]+$/);
  const runPath = new URL(page.url()).pathname;
  let report: ReturnType<typeof RunReportFile.parse> | undefined;
  await expect.poll(async () => {
    const response = await page.request.get("/api" + runPath + "/export");
    expect(response.ok()).toBe(true);
    report = RunReportFile.parse(await response.json());
    return report.run.status;
  }, { timeout: 180_000, intervals: [1000, 2000, 4000] }).toBe("completed");
  const decision = report!.steps.find((step) => step.nodeId === original.id)!;
  expect(report!.run.agentId).toBe(agentPath.split("/").at(-1));
  expect(report!.run.version).toBe(frozen.version.number);
  expect(report!.run.input).toEqual({ payload });
  expect(decision.output).toEqual({ matched: "文字命中", next: original.condition!.branches[0].next });
  await expect(page.getByText("运行已完成", { exact: true })).toBeVisible();
  await testInfo.attach("真实设计修复与冻结版本运行", { body: JSON.stringify({ before: before.workflow.nodes[original.id].condition, after: updated, resultText, unchangedVersion: unchangedVersion.version.number, frozenCondition: unchangedVersion.manifest.workflowSnapshot.nodes[original.id].condition, run: { input: report!.run.input, version: report!.run.version, decision: decision.output } }, null, 2), contentType: "application/json" });
  expect(pageErrors).toEqual([]);
});
